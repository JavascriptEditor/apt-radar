def codes_for(sido: str | None = None) -> list[str]:
    return [r["code"] for r in REGIONS if sido is None or r["sido"] == sido]


def group_of(code: str, live: dict | None = None) -> str:
    if live and code in live:
        return live[code].get("group") or code
    r = BY_CODE.get(code)
    return r["group"] if r else code


def name_of(code: str, live: dict | None = None) -> str:
    if live and code in live:
        return live[code].get("name") or code
    r = BY_CODE.get(code)
    return r["name"] if r else code


def sido_of(code: str) -> str:
    return code[:2]


def short_name(code: str, live: dict | None = None) -> str:
    """'수원시 영통구' → '수원 영통구', '성남시 분당구' → '성남 분당구', '강남구' → '강남구'."""
    n = name_of(code, live)
    return n.replace("시 ", " ")


def all_codes(live: dict | None = None) -> list[dict]:
    """정적 목록 + 탐색으로 찾은 코드. 적재 순서(서울→경기→인천) 유지."""
    out = list(REGIONS)
    seen = {r["code"] for r in out}
    for code, info in sorted((live or {}).items()):
        if code in seen:
            continue
        out.append({"code": code, "sido": code[:2], "name": info.get("name", code),
                    "group": info.get("group") or code, "note": "자동 탐색"})
    out.sort(key=lambda r: (SIDO_ORDER.index(r["sido"]) if r["sido"] in SIDO_ORDER else 9, r["code"]))
    return out


def parse_filter(text: str | None, live: dict | None = None) -> list[str]:
    """REGION_FILTER: '서울', '서울,경기', '11680,41135' 등."""
    if not text or not text.strip():
        return [r["code"] for r in all_codes(live)]
    want: list[str] = []
    for tok in text.replace(" ", "").split(","):
        if not tok:
            continue
        sido = next((k for k, v in SIDO_NAME.items() if v == tok), None)
        if sido:
            want += [r["code"] for r in all_codes(live) if r["sido"] == sido]
        elif tok.isdigit() and len(tok) == 5:
            want.append(tok)
        else:
            want += [r["code"] for r in all_codes(live) if tok in r["name"]]
    seen, out = set(), []
    for c in want:
        if c not in seen:
            seen.add(c)
            out.append(c)
    return out


def guess_new_gu(umd_names: set[str], sido: str, fallback_group: str | None) -> tuple[str, str]:
    """훑어보다 찾은 코드의 법정동 집합으로 (이름, 묶음코드)를 추정."""
    best, best_hit = None, 0
    for gu, (grp, dongs) in NEW_GU_DONGS.items():
        if grp[:2] != sido:
            continue
        hit = len(umd_names & set(dongs))
        if hit > best_hit:
            best, best_hit = (gu, grp), hit
    if best and best_hit >= 1:
        return best
    return ("신설구", fallback_group or "")
